        <p>
            Counts follow the dates shown. A dash means a period has missing reports; zero means no
            fires were reported. Grey districts have no reported count for the selection.
        </p>
        <p>
            The 2026 paddy counts come from <a
                class="underline"
                href="https://creams.iari.res.in/geokrishi/">ICAR-IARI</a
            >. Older counts use NRSC. Their methods differ. Satellite observations can repeat,
            including across state borders, so totals do not represent distinct physical fires or
            farms.
        </p>
        <p>
            District outlines use IARI / Survey of India boundaries. Hansi is derived from <a
                class="underline"
                href="https://yashveeeeeeer.github.io/india-geodata/">LGD blocks</a
            > using the district's published block membership. Counts retain the source's district assignments,
            which may differ from the outlines. Historical records may use older boundaries.
        </p>
        <p>
            Satellite imagery is a landscape reference, not imagery captured on the selected fire
            date. Acquisition times in popups retain the publisher's clock; its timezone is
            unspecified.
        </p>
